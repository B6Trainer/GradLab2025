package com.bala.practice.corejava.basics.operators;

public class ArithmeticOperators {
    public static void main(String[] args) {
        int integerA = 10;
        int integerB = 5;

        // Addition
        int sum = integerA + integerB;
        System.out.println("Sum: " + sum); // Output: 15

        // Subtraction
        int difference = integerA - integerB;
        System.out.println("Difference: " + difference); // Output: 5

        // Multiplication
        int product = integerA * integerB;
        System.out.println("Product: " + product); // Output: 50

        // Division
        int quotient = integerA / integerB;
        System.out.println("Quotient: " + quotient); // Output: 2

        // Modulus
        int remainder = integerA % integerB;
        System.out.println("Remainder: " + remainder); // Output: 0
    }
}

