package com.bala.practice.cleancode;

public class Singer {

    public static double singSong(double x, double y) {
        return x + y;
    }

    public static double learnSong(double x, double y) {
        return x - y;
    }

    public static double practiceSinging(double x, double y) {
        return x * y;
    }

    public static double memoriseLyrics(double x, double y) {
        return x / y;
    }

    public static void main(String[] args) {
        singSong(1,2);
        learnSong(1,2);
        practiceSinging(1,2);
        memoriseLyrics(1,2);
    }

    //TEst file
}

